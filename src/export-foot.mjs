// The foot target: one foot.ini fragment holding both modes.
//
// The input is the theme JSON the OpenCode target already ships
// (`opencode/dist/<name>.json`), not the palettes — that is why `npm run export`
// chains the exporters with `&&`, and why every terminal target carries the same
// bytes. Reading a built file is also why `hue.accent` here is a string to follow
// before it can be indexed by step.
//
// One file covers both modes: `[colors-dark]` and `[colors-light]` sit in the
// same fragment, so there is no mode parameter and no mode branch — the ramps
// already flip, so `.300` is the normal ANSI colour and `.200` the bright one in
// both. foot names the sixteen slots numerically (`regular0`…`bright7`), its
// magenta is the pack's purple, and there is no orange slot.
//
// Targets foot ≥ 1.26: `[colors]`/`[colors2]` are deprecated in 1.26 and removed
// in 1.28, and `cursor` moved into the colour section in 1.23.

import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const PROJECT_ROOT = fileURLToPath(new URL("..", import.meta.url));

/** The pack's purple is foot's magenta. */
const CHROMATIC = ["red", "green", "yellow", "blue", "purple", "cyan"];
/** The sixteen slots in ANSI order: `regular0`…`regular7` then `bright0`…`bright7`. */
const SLOTS = [
  ["gray", "900"],
  ...CHROMATIC.map((hue) => [hue, "300"]),
  ["gray", "300"],
  ["gray", "600"],
  ...CHROMATIC.map((hue) => [hue, "200"]),
  ["gray", "100"],
];

/** A hue entry is either a ramp or a whole-hue alias; follow the alias to the ramp. */
const ramp = (tree, name) =>
  typeof tree.hue[name] === "string"
    ? ramp(tree, tree.hue[name].replace("$hue.", "").split(".")[0])
    : tree.hue[name];

/**
 * One theme, both modes, as a foot.ini fragment.
 *
 * foot wants six-digit hex with no `#` and `key=value` with no spaces; `cursor`
 * is the one key holding two values, text colour first.
 *
 * @param {object} theme a built theme file
 * @param {string} name the theme's name, for the header line
 * @returns {string}
 */
export function footTheme(theme, name) {
  const bare = (hex) => hex.slice(1);
  const section = (label, tree) => {
    const hex = ([hue, at]) => bare(ramp(tree, hue)[at]);
    const accent = bare(ramp(tree, "accent")["300"]);
    return [
      `[colors-${label}]`,
      `background=${bare(tree.background.base)}`,
      `foreground=${bare(tree.text.base)}`,
      ...SLOTS.map((slot, index) => `${index < 8 ? "regular" : "bright"}${index % 8}=${hex(slot)}`),
      `selection-foreground=${bare(tree.text.base)}`,
      `selection-background=${bare(tree.background.raised.high)}`,
      `cursor=${bare(tree.background.base)} ${accent}`,
      `urls=${accent}`,
    ];
  };
  const lines = [
    `# ${name} — generated by src/export-foot.mjs; edit the palette, not this file.`,
    "",
    ...section("dark", theme.dark),
    "",
    ...section("light", theme.light),
  ];
  return `${lines.join("\n")}\n`;
}

/**
 * Write every built theme as a foot.ini fragment, one file per theme.
 *
 * @param {{themesDir: string, outDir: string}} paths
 * @returns {{themes: string[], errors: string[]}}
 */
export function exportFoot({ themesDir, outDir }) {
  mkdirSync(outDir, { recursive: true });
  const themes = [];
  const errors = [];
  const names = readdirSync(themesDir)
    .filter((file) => file.endsWith(".json"))
    .map((file) => file.slice(0, -".json".length))
    .sort();

  for (const name of names) {
    try {
      const theme = JSON.parse(readFileSync(join(themesDir, `${name}.json`), "utf8"));
      writeFileSync(join(outDir, `${name}.ini`), footTheme(theme, name));
      themes.push(name);
    } catch (error) {
      errors.push(`${name}: ${error.message}`);
    }
  }

  return { themes, errors };
}

function main() {
  const { themes, errors } = exportFoot({
    themesDir: join(PROJECT_ROOT, "opencode", "dist"),
    outDir: join(PROJECT_ROOT, "foot", "dist"),
  });
  for (const name of themes) console.log(`${name}: exported`);
  for (const error of errors) console.error(error);
  if (errors.length > 0) process.exitCode = 1;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) main();
